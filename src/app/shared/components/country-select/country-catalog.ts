export const countries = codes.map(code => ({
  code,
  name: names.of(code) ?? code,
  flag: 'iti__' + code.toLowerCase(),
})).sort((a, b) => collator.compare(a.name, b.name));

export function normalizeCountryName(value: string): string {
  return value.trim().toLowerCase().normalize('NFD').replace(/[\u0300-\u036f]/g, '');
}

export function findCountry(value: string) {
  const normalized = normalizeCountryName(value);
  return countries.find(country =>
    country.code.toLowerCase() === normalized ||
    normalizeCountryName(country.name) === normalized ||
    normalizeCountryName(englishNames.of(country.code) ?? '') === normalized
  );
}
